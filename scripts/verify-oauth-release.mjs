import assert from 'node:assert/strict';
const origin = new URL(process.argv[2]);
const get = path => fetch(new URL(path, origin), { headers: { Accept: 'text/html' }, redirect: 'manual', signal: AbortSignal.timeout(10000) });
const page = await get('/login?return=%2Fme');
assert.equal(page.status, 200, 'Login page must return HTTP 200');
assert.ok((await page.text()).includes('/auth/github/start?return=%2Fme'), 'Login button must preserve the destination');
const start = await get('/auth/github/start?return=%2Fme');
assert.equal(start.status, 302, 'GitHub OAuth start must redirect');
const authorization = new URL(start.headers.get('location'));
assert.equal(authorization.origin, 'https://github.com');
assert.equal(authorization.pathname, '/login/oauth/authorize');
assert.equal(authorization.searchParams.get('redirect_uri'), 'https://www.cnmcp.com/auth/github/callback');
assert.ok(authorization.searchParams.has('client_id'));
assert.ok(/^[a-f0-9]{64}$/.test(authorization.searchParams.get('state') ?? ''));
const binding = start.headers.getSetCookie().find(value => value.startsWith('__Host-cnmcp_oauth='));
assert.ok(binding && binding.includes('Secure; HttpOnly; SameSite=Lax'), 'OAuth browser cookie has incorrect security attributes');
const expired = await get('/auth/github/callback');
assert.equal(expired.status, 303, 'Invalid callback should lead to the login page');
assert.equal(expired.headers.get('location'), '/login?error=expired');
console.log('OAuth start, browser cookie, callback URL, and invalid-state handling verified at', origin.origin);
